// Turns one 16x16 GIF/PNG per state into the exact Timebox Evo byte messages,
// using node-divoom-timebox-evo, and writes them to firmware/include/states.h.
// The firmware only replays these bytes; it never encodes images itself.
//
// Source per state, first match wins:
//   art/custom/<state>.gif | art/custom/<state>.png   (your own art)
//   art/gif/<state>.gif                                (starter art, `npm run art`)
//
// Also writes firmware/test/host/fixtures.h: library output the firmware's own
// text/brightness encoder is checked against.
const fs = require('fs');
const path = require('path');
const Divoom = require('node-divoom-timebox-evo');
const { STATES, paletteFor } = require('./art/sprites');

const ROOT = path.join(__dirname, '..');
const OUT_HEADER = path.join(ROOT, 'firmware', 'include', 'states.h');
const OUT_FIXTURES = path.join(ROOT, 'firmware', 'test', 'host', 'fixtures.h');
const evo = new Divoom.TimeboxEvo();

function sourceFor(state) {
  for (const f of [`custom/${state}.gif`, `custom/${state}.png`, `gif/${state}.gif`]) {
    const p = path.join(__dirname, 'art', f);
    if (fs.existsSync(p)) return { file: p, custom: f.startsWith('custom/') };
  }
  throw new Error(`no art for state '${state}' (run \`npm run art\` first)`);
}

// Check framing: 01 | len LE | payload | crc LE | 02, len = payload + 2,
// crc = sum(len bytes + payload) & 0xffff.
function checkFrame(buf, where) {
  const n = buf.length;
  if (buf[0] !== 0x01 || buf[n - 1] !== 0x02) throw new Error(`${where}: bad start/end byte`);
  const len = buf[1] | (buf[2] << 8);
  if (len !== n - 4) throw new Error(`${where}: length field ${len}, expected ${n - 4}`);
  let sum = 0;
  for (let i = 1; i < n - 3; i++) sum += buf[i];
  const crc = buf[n - 3] | (buf[n - 2] << 8);
  if ((sum & 0xffff) !== crc) throw new Error(`${where}: bad checksum`);
}

// One TimeboxEvoMessage -> one Buffer (the library splits long ones into
// several write chunks; for us they are one message on the wire).
const messagesOf = (msgArray) => msgArray.map((m) => Buffer.from(m.message, 'hex'));

async function animationMessages(state) {
  const { file, custom } = sourceFor(state);
  const req = evo.createRequest('animation');
  const frames = await req.read(file);
  if (!custom && STATES[state]) {
    // the library resizes frames; make sure our pixel art survived untouched
    const allowed = new Set(Object.values(paletteFor(state)));
    frames.forEach((fr, i) => {
      fr.getColorsAndPixels().colors.forEach((c) => {
        if (!allowed.has(c)) throw new Error(`${state} frame ${i}: unexpected colour #${c} after resize`);
      });
    });
  }
  return { msgs: messagesOf(frames.asDivoomMessages()), file: path.relative(__dirname, file) };
}

function cBytes(buf) {
  const parts = [];
  for (let i = 0; i < buf.length; i += 16) {
    parts.push('  ' + [...buf.subarray(i, i + 16)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', '));
  }
  return parts.join(',\n');
}

async function main() {
  const states = {};
  for (const name of Object.keys(STATES)) states[name] = await animationMessages(name);
  // Pseudo-state: the Evo's built-in clock (full-screen, white).
  states.clock = {
    msgs: messagesOf(evo.createRequest('time', { color: '#ffffff' }).messages),
    file: '(built-in time channel)',
  };

  let h = '// Generated by tools/build-states.js. Do not edit; run `npm run build` in tools/.\n';
  h += '#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n';
  h += '#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n';
  h += 'struct EvoMessage { const uint8_t* data; uint16_t len; };\n';
  h += 'struct EvoStateAnim { const char* name; const EvoMessage* messages; uint8_t count; };\n\n';
  let total = 0;
  for (const [name, { msgs, file }] of Object.entries(states)) {
    h += `// ${name}: ${msgs.length} message(s) from ${file}\n`;
    msgs.forEach((m, i) => {
      checkFrame(m, `${name}[${i}]`);
      total += m.length;
      h += `static const uint8_t evo_${name}_${i}[] PROGMEM = {\n${cBytes(m)}\n};\n`;
    });
    h += `static const EvoMessage evo_${name}_msgs[] = {\n`;
    h += msgs.map((m, i) => `  { evo_${name}_${i}, ${m.length} },`).join('\n') + '\n};\n\n';
    console.log(`  ${name.padEnd(13)} ${msgs.length} msg, ${msgs.reduce((a, m) => a + m.length, 0)} bytes  <- ${file}`);
  }
  h += 'static const EvoStateAnim EVO_STATES[] = {\n';
  h += Object.entries(states).map(([n, { msgs }]) => `  { "${n}", evo_${n}_msgs, ${msgs.length} },`).join('\n');
  h += '\n};\nstatic const size_t EVO_STATE_COUNT = sizeof(EVO_STATES) / sizeof(EVO_STATES[0]);\n';
  fs.writeFileSync(OUT_HEADER, h);
  console.log(`  wrote firmware/include/states.h (${total} bytes of messages)`);

  // Fixtures for the firmware's on-device encoders.
  const text = evo.createRequest('text', { text: 'Hi Evo!' });
  const textMsgs = messagesOf(text.messages);
  const bright = messagesOf(evo.createRequest('brightness', { brightness: 50 }).messages);
  let fx = '// Generated by tools/build-states.js from node-divoom-timebox-evo output.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n';
  fx += 'static const char FIX_TEXT[] = "Hi Evo!";\n';
  textMsgs.forEach((m, i) => { fx += `static const uint8_t FIX_TEXT_${i}[] = {\n${cBytes(m)}\n};\n`; });
  fx += `static const uint8_t* const FIX_TEXT_MSGS[] = { ${textMsgs.map((_, i) => `FIX_TEXT_${i}`).join(', ')} };\n`;
  fx += `static const size_t FIX_TEXT_LENS[] = { ${textMsgs.map((m) => m.length).join(', ')} };\n`;
  fx += `static const size_t FIX_TEXT_COUNT = ${textMsgs.length};\n\n`;
  fx += `static const uint8_t FIX_BRIGHTNESS_50[] = {\n${cBytes(bright[0])}\n};\n`;
  fs.mkdirSync(path.dirname(OUT_FIXTURES), { recursive: true });
  fs.writeFileSync(OUT_FIXTURES, fx);
  console.log('  wrote firmware/test/host/fixtures.h');
}

main().catch((e) => { console.error(e.message || e); process.exit(1); });
