// Turns one GIF/PNG per state into the exact Timebox Evo byte messages and
// writes them to firmware/include/states.h. The firmware only replays these
// bytes; it never encodes images itself.
//
// Source per state, first match wins:
//   art/custom/<state>.gif | art/custom/<state>.png   (your own art)
//   art/gif/<state>.gif                                (starter art, `npm run art`)
const fs = require('fs');
const path = require('path');
const encode = require('./evo-encode');
const { loadArt } = require('./load-art');
const { STATES, paletteFor } = require('./art/sprites');

const OUT_HEADER = path.join(__dirname, '..', 'firmware', 'include', 'states.h');

function sourceFor(state, { starterOnly = false } = {}) {
  const candidates = starterOnly
    ? [`gif/${state}.gif`]
    : [`custom/${state}.gif`, `custom/${state}.png`, `gif/${state}.gif`];
  for (const f of candidates) {
    const p = path.join(__dirname, 'art', f);
    if (fs.existsSync(p)) return { file: p, custom: f.startsWith('custom/') };
  }
  throw new Error(`no art for state '${state}' (run \`npm run art\` first)`);
}

// Check framing: 01 | len LE | payload | crc LE | 02, len = payload + 2,
// crc = sum(len bytes + payload) & 0xffff.
function checkFrame(buf, where) {
  const n = buf.length;
  if (buf[0] !== 0x01 || buf[n - 1] !== 0x02) throw new Error(`${where}: bad start/end byte`);
  const len = buf[1] | (buf[2] << 8);
  if (len !== n - 4) throw new Error(`${where}: length field ${len}, expected ${n - 4}`);
  let sum = 0;
  for (let i = 1; i < n - 3; i++) sum += buf[i];
  const crc = buf[n - 3] | (buf[n - 2] << 8);
  if ((sum & 0xffff) !== crc) throw new Error(`${where}: bad checksum`);
}

async function stateMessages(state, opts) {
  const { file, custom } = sourceFor(state, opts);
  const { frames, animated } = await loadArt(file);
  if (!custom) {
    // make sure the starter art came through the GIF round trip untouched
    const allowed = new Set(Object.values(paletteFor(state)));
    frames.forEach(({ pixels }, i) => pixels.forEach((c) => {
      if (!allowed.has(c)) throw new Error(`${state} frame ${i}: unexpected colour #${c}`);
    }));
  }
  const msgs = animated ? encode.animation(frames) : encode.picture(frames[0].pixels);
  return { msgs, file: path.relative(__dirname, file) };
}

function cBytes(buf) {
  const parts = [];
  for (let i = 0; i < buf.length; i += 16) {
    parts.push('  ' + [...buf.subarray(i, i + 16)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', '));
  }
  return parts.join(',\n');
}

// Returns the text of states.h. starterOnly ignores art/custom (used by tests).
async function buildHeader(opts = {}, log = () => {}) {
  const states = {};
  for (const name of Object.keys(STATES)) states[name] = await stateMessages(name, opts);
  // Pseudo-state: the Evo's built-in clock (full-screen, white).
  states.clock = { msgs: encode.clock('ffffff'), file: '(built-in time channel)' };

  let h = '// Generated by tools/build-states.js. Do not edit; run `npm run build` in tools/.\n';
  h += '#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n';
  h += '#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n';
  h += 'struct EvoMessage { const uint8_t* data; uint16_t len; };\n';
  h += 'struct EvoStateAnim { const char* name; const EvoMessage* messages; uint8_t count; };\n\n';
  let total = 0;
  for (const [name, { msgs, file }] of Object.entries(states)) {
    if (msgs.length > 255) throw new Error(`${name}: ${msgs.length} messages; max is 255 (fewer frames or colours)`);
    h += `// ${name}: ${msgs.length} message(s) from ${file}\n`;
    msgs.forEach((m, i) => {
      checkFrame(m, `${name}[${i}]`);
      total += m.length;
      h += `static const uint8_t evo_${name}_${i}[] PROGMEM = {\n${cBytes(m)}\n};\n`;
    });
    h += `static const EvoMessage evo_${name}_msgs[] = {\n`;
    h += msgs.map((m, i) => `  { evo_${name}_${i}, ${m.length} },`).join('\n') + '\n};\n\n';
    log(`  ${name.padEnd(13)} ${msgs.length} msg, ${msgs.reduce((a, m) => a + m.length, 0)} bytes  <- ${file}`);
  }
  h += 'static const EvoStateAnim EVO_STATES[] = {\n';
  h += Object.entries(states).map(([n, { msgs }]) => `  { "${n}", evo_${n}_msgs, ${msgs.length} },`).join('\n');
  h += '\n};\nstatic const size_t EVO_STATE_COUNT = sizeof(EVO_STATES) / sizeof(EVO_STATES[0]);\n';
  log(`  wrote firmware/include/states.h (${total} bytes of messages)`);
  return h;
}

module.exports = { buildHeader };

if (require.main === module) {
  buildHeader({}, console.log)
    .then((h) => fs.writeFileSync(OUT_HEADER, h))
    .catch((e) => { console.error(e.message || e); process.exit(1); });
}
